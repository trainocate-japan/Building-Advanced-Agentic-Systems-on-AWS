"""
モジュール 2: コンテキスト分離 - マルチエージェント境界

コンテキストを専門エージェント間で分配し、
各エージェントが必要最小限の情報のみを持つパターンを実装します。

メリット:
- 各エージェントのコンテキストが小さい → 高品質な回答
- ディストラクションの排除
- 並列実行が可能 → レイテンシー改善
- 障害の分離

マルチエージェントコンテキスト分散戦略:
- 簡単な事実確認: 1 エージェント、3〜10 回のツール呼び出し
- 複雑な研究: 10+ エージェント、役割を明確に分離
"""

import asyncio
import time
from strands import Agent, tool


# =============================================================================
# 専門エージェント（最小コンテキスト）
# =============================================================================

# 注文調査エージェント - 注文データのみをコンテキストに持つ
order_agent = Agent(
    model="us.amazon.nova-lite-v1:0",  # 軽量モデルで十分
    system_prompt="""あなたは注文データの専門家です。
注文情報の検索と状態確認のみを行います。
回答は JSON 形式で簡潔に返してください。"""
)

# 在庫エージェント - 在庫データのみ
inventory_agent = Agent(
    model="us.amazon.nova-lite-v1:0",
    system_prompt="""あなたは在庫管理の専門家です。
商品の在庫状況と配送予定のみを回答します。
回答は JSON 形式で簡潔に返してください。"""
)

# 顧客対応エージェント - 対話スキルに集中
customer_facing_agent = Agent(
    model="us.amazon.nova-pro-v1:0",  # 対話品質が重要なので高性能モデル
    system_prompt="""あなたはカスタマーサポートの最終回答を生成するエージェントです。
他のエージェントから収集された情報を基に、顧客に分かりやすく回答を生成します。
丁寧で具体的な回答を心がけてください。"""
)


# =============================================================================
# オーケストレーター（コンテキスト分離を実現）
# =============================================================================

@tool
def lookup_order(order_id: str) -> str:
    """注文情報を専門エージェントに問い合わせる（分離されたコンテキスト）

    Args:
        order_id: 注文ID
    """
    # 注文エージェントには注文関連の最小コンテキストのみ渡す
    result = order_agent(
        f"注文ID: {order_id} の状態を確認してください。"
        f"注文日: 2026-08-10, 商品: 液晶モニター27インチ, "
        f"状態: 配送済み, 配送日: 2026-08-12"
    )
    return str(result)


@tool
def check_inventory(product_id: str) -> str:
    """在庫状況を専門エージェントに問い合わせる（分離されたコンテキスト）

    Args:
        product_id: 商品ID
    """
    # 在庫エージェントには在庫関連の最小コンテキストのみ渡す
    result = inventory_agent(
        f"商品ID: {product_id} の在庫状況を確認してください。"
        f"商品名: 液晶モニター27インチ, 在庫: 15台, "
        f"次回入荷: 2026-08-20, 配送リードタイム: 2日"
    )
    return str(result)


# 統合オーケストレーター
orchestrator = Agent(
    model="us.amazon.nova-pro-v1:0",
    system_prompt="""あなたはカスタマーサポートのオーケストレーターです。
顧客の問い合わせを分析し、必要な情報を専門エージェント（ツール）から収集してください。

方針:
- 各ツールには必要最小限の情報のみ渡す
- 複数の情報が必要な場合は並列で収集
- 収集した情報を統合して最終回答を生成""",
    tools=[lookup_order, check_inventory]
)


# =============================================================================
# デモ: コンテキスト分離 vs 一括処理の比較
# =============================================================================

def demo_context_isolation():
    """コンテキスト分離パターンのデモ"""

    print("=" * 70)
    print(" コンテキスト分離: マルチエージェント境界によるコンテキスト最適化")
    print("=" * 70)

    # シナリオ
    customer_query = (
        "注文 ORD-2026-78901 の商品が破損していました。"
        "交換品の在庫があるか確認して、交換手続きを教えてください。"
    )

    print(f"\n  顧客問い合わせ: {customer_query}")

    # ─── パターン 1: 一括処理（アンチパターン） ───
    print(f"\n{'─' * 70}")
    print("  [パターン 1] 一括処理（アンチパターン）")
    print(f"{'─' * 70}")

    # 大きなコンテキストを1つのエージェントに渡す
    huge_context = f"""
    顧客情報: 田中太郎、会員ID: MEM-12345、プラン: Premium
    注文履歴: ORD-2026-78901（液晶モニター）、ORD-2026-67890（キーボード）...他30件
    過去の問い合わせ履歴: 15件（技術サポート5件、請求3件、返品7件）
    商品カタログ: 液晶モニター27インチ（在庫15台）、32インチ（在庫3台）...他500件
    配送ポリシー: 標準2-3日、速達1日、離島5-7日
    返品ポリシー: 30日以内全額、31-90日50%、破損品は即交換
    プロモーション情報: 夏季セール実施中、モニター15%OFF
    """

    monolithic_agent = Agent(
        model="us.amazon.nova-pro-v1:0",
        system_prompt="あなたはカスタマーサポートです。以下の全情報を使って回答してください。"
    )

    start_time = time.time()
    monolithic_result = monolithic_agent(f"{huge_context}\n\n質問: {customer_query}")
    monolithic_time = time.time() - start_time

    print(f"  コンテキストサイズ: {len(huge_context)} 文字（全情報を1エージェントに）")
    print(f"  処理時間: {round(monolithic_time * 1000)}ms")
    print(f"  回答: {str(monolithic_result)[:200]}...")

    # ─── パターン 2: コンテキスト分離（推奨） ───
    print(f"\n{'─' * 70}")
    print("  [パターン 2] コンテキスト分離（推奨）")
    print(f"{'─' * 70}")

    start_time = time.time()

    # オーケストレーターが必要な情報のみを専門エージェントに問い合わせ
    isolated_result = orchestrator(customer_query)
    isolated_time = time.time() - start_time

    print(f"  各エージェントのコンテキスト: 最小限（必要な情報のみ）")
    print(f"  処理時間: {round(isolated_time * 1000)}ms")
    print(f"  回答: {str(isolated_result)[:200]}...")

    # ─── 比較まとめ ───
    print(f"\n{'─' * 70}")
    print("  [比較まとめ]")
    print(f"{'─' * 70}")
    print(f"""
    ┌──────────────────────┬───────────────────┬───────────────────┐
    │ 観点                  │ 一括処理          │ コンテキスト分離   │
    ├──────────────────────┼───────────────────┼───────────────────┤
    │ コンテキストサイズ     │ 大（全情報）      │ 小（必要最小限）  │
    │ ディストラクション     │ 高い             │ 低い              │
    │ 回答品質              │ 中（情報過多）    │ 高（集中）        │
    │ 並列実行              │ 不可             │ 可能              │
    │ 障害影響              │ 全体に波及       │ 部分的            │
    │ コスト                │ 高い             │ 効率的            │
    └──────────────────────┴───────────────────┴───────────────────┘
    """)

    print("  [委任の指針]")
    print("  - 簡単な事実確認: 1 エージェント、3〜10 回のツール呼び出し")
    print("  - 複雑な研究: 10+ エージェント、役割を明確に分離")
    print("  - オーケストレーターには委任方法を明示的に指示する")


if __name__ == "__main__":
    demo_context_isolation()

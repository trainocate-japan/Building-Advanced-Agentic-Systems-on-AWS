"""
モジュール 1: MCP (Model Context Protocol) を使用したツールとしてのエージェント

専門エージェントを MCP サーバーのツールとして公開し、
オーケストレーターエージェントから呼び出すパターンを実装します。

ツールとしてのエージェントパターンの特徴:
- プライマリオーケストレーターがツールとしてエージェントを呼び出す
- 疎結合を実現し、再利用性を促進
- 複数のユースケースで共有される専門化された機能

AgentCore Gateway との統合:
- MCP サーバーを AgentCore Gateway に登録
- セマンティックツール検索が可能
- 認証・認可は Gateway が一元管理
"""

from strands import Agent, tool


# =============================================================================
# 専門エージェントをツールとして定義
# =============================================================================

@tool
def technical_support_agent(query: str) -> str:
    """技術的な問題のトラブルシューティングを行う専門エージェント。
    ログイン問題、API エラー、パフォーマンス問題などに対応します。

    Args:
        query: 技術的な問い合わせ内容
    """
    agent = Agent(
        model="us.amazon.nova-lite-v1:0",
        system_prompt="""あなたは技術サポートの専門エージェントです。
ユーザーの技術的な問題に対して、具体的なトラブルシューティング手順を提供してください。
回答は簡潔かつ実用的にしてください。"""
    )
    result = agent(f"以下の技術的な問題を解決してください: {query}")
    return str(result)


@tool
def billing_support_agent(query: str) -> str:
    """請求・支払いに関する問い合わせに対応する専門エージェント。
    料金の説明、返金処理、プラン変更などに対応します。

    Args:
        query: 請求に関する問い合わせ内容
    """
    agent = Agent(
        model="us.amazon.nova-lite-v1:0",
        system_prompt="""あなたは請求サポートの専門エージェントです。
ユーザーの請求に関する問い合わせに対して、正確で丁寧な案内を提供してください。"""
    )
    result = agent(f"以下の請求に関する問い合わせに対応してください: {query}")
    return str(result)


@tool
def product_recommendation_agent(query: str) -> str:
    """商品レコメンデーションを行う専門エージェント。
    ユーザーの要件に基づいた商品提案を行います。

    Args:
        query: 商品に関する問い合わせ内容
    """
    agent = Agent(
        model="us.amazon.nova-lite-v1:0",
        system_prompt="""あなたは商品レコメンデーションの専門エージェントです。
ユーザーの要件と予算に合わせた具体的な商品提案を行ってください。"""
    )
    result = agent(f"以下の要件に合う商品を提案してください: {query}")
    return str(result)


# =============================================================================
# オーケストレーターエージェント（ツールとしてエージェントを呼び出す）
# =============================================================================

orchestrator = Agent(
    model="us.amazon.nova-pro-v1:0",
    system_prompt="""あなたはカスタマーサポートのオーケストレーターです。
顧客の問い合わせを適切な専門エージェント（ツール）にルーティングしてください。

利用可能なツール:
- technical_support_agent: 技術的な問題
- billing_support_agent: 請求・支払い関連
- product_recommendation_agent: 商品レコメンデーション

問い合わせ内容を分析し、最適なツールを選択して呼び出してください。
複数のツールが必要な場合は、順番に呼び出してください。""",
    tools=[technical_support_agent, billing_support_agent, product_recommendation_agent]
)


# =============================================================================
# デモ実行
# =============================================================================

def run_mcp_tool_pattern():
    """MCP ツールとしてのエージェントパターンをデモ"""

    print("=" * 60)
    print(" ツールとしてのエージェント: MCP パターンデモ")
    print("=" * 60)
    print("""
    アーキテクチャ:
    ┌────────────────────────────────────────────┐
    │          Orchestrator Agent                  │
    │      (ルーティング & 統合)                    │
    ├────────────────────────────────────────────┤
    │  ┌─────────┐ ┌─────────┐ ┌─────────────┐  │
    │  │Technical│ │Billing  │ │ Product     │  │
    │  │ Tool    │ │ Tool    │ │ Recommend   │  │
    │  │(Agent)  │ │(Agent)  │ │ Tool(Agent) │  │
    │  └─────────┘ └─────────┘ └─────────────┘  │
    └────────────────────────────────────────────┘
    """)

    # テスト問い合わせ
    queries = [
        "ログインしようとするとエラー403が出ます。アカウントはあるはずなのですが。",
        "先月のサブスクリプション更新で二重課金されたようです。返金してもらえますか？",
        "リモートワーク用にノイズキャンセリングヘッドホンが欲しいです。予算2万円。",
    ]

    for i, query in enumerate(queries, 1):
        print(f"\n{'─' * 60}")
        print(f"  問い合わせ {i}: {query}")
        print(f"{'─' * 60}")

        # オーケストレーターが自動でツール（エージェント）を選択・呼び出し
        print("  [Orchestrator] ツール選択 & 実行中...")
        result = orchestrator(query)
        print(f"\n  [最終回答]")
        print(f"  {result}")

    # -------------------------------------------------------------------
    # AgentCore Gateway + MCP の統合説明
    # -------------------------------------------------------------------
    print(f"\n{'─' * 60}")
    print("  [参考] 本番環境での AgentCore Gateway 統合")
    print(f"{'─' * 60}")
    print("""
    本番環境では AgentCore Gateway を使用して MCP サーバーを一元管理します:

    1. MCP サーバーを Gateway に登録
       - ツールの説明とスキーマを登録
       - 認証情報を Gateway が管理

    2. セマンティックツール検索
       - エージェントがクエリに基づいてツールを自動発見
       - 説明文のセマンティック類似性で最適ツールを選択

    3. 認証の一元化
       - OAuth 2.0 (2LO/3LO) をサポート
       - AWS IAM、Lambda、MCP サーバーの各ターゲットに対応
       - AgentCore Identity と連携

    4. A2A (Agent-to-Agent) プロトコル
       - プラットフォームを跨いだエージェント間通信
       - Agent Card でケーパビリティをアドバタイズ
       - タスクオブジェクトでワークを管理
    """)

    print("\n" + "=" * 60)
    print(" MCP ツールパターンデモ完了")
    print("=" * 60)
    print("\n[Key Takeaways]")
    print("1. 各エージェントを @tool として定義 → 疎結合で再利用可能")
    print("2. オーケストレーターが自動でルーティング → 柔軟な問い合わせ対応")
    print("3. AgentCore Gateway で本番環境の認証・発見を一元管理")
    print("4. MCP 標準で異なるプラットフォーム間の相互運用が可能")


if __name__ == "__main__":
    run_mcp_tool_pattern()
